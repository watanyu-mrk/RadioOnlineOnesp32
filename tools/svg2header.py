#!/usr/bin/env python3
"""Convert 24x24 pixel-art SVG icons into 1-bit masks for the ST7701 panel.

Source set: Pixelarticons (https://github.com/halfmage/pixelarticons, MIT).
They are rectilinear pixel art, so a small path parser (M/m/L/l/H/h/V/v/Z) plus a scanline
fill is enough - no cairosvg / PIL needed, which matters because the only python on this
machine is the one PlatformIO ships.

Output: one `static const uint32_t ICON_xxx[24]` per icon, bit x of row y set = pixel on.
That is 96 bytes per icon in flash and lets the UI draw it in any colour at any integer
scale (drawIcon() in src/ui/ui_status.cpp), so the whole screen shares one palette.

Usage:
  python tools/svg2header.py --out include/ui_icons.h \
      radio=assets/icons/svg/radio.svg music=assets/icons/svg/music.svg --preview
"""

import argparse
import re

CMD_RE = re.compile(r"[MmLlHhVvZz]|-?\d*\.?\d+")


def parse_paths(svg_text):
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg_text)
    shapes = []
    for d in paths:
        tokens = CMD_RE.findall(d)
        i = 0
        cmd = None
        x = y = 0.0
        start = None
        sub = []
        while i < len(tokens):
            t = tokens[i]
            if t.isalpha():
                cmd = t
                i += 1
                if cmd in "Zz":
                    if len(sub) > 2:
                        shapes.append(sub)
                    sub = []
                    if start:
                        x, y = start
                    continue
            def num():
                nonlocal i
                v = float(tokens[i])
                i += 1
                return v

            if cmd in "Mm":
                nx, ny = num(), num()
                if cmd == "M":
                    x, y = nx, ny
                else:
                    x, y = x + nx, y + ny
                if len(sub) > 2:
                    shapes.append(sub)
                sub = [(x, y)]
                start = (x, y)
                cmd = "L" if cmd == "M" else "l"
            elif cmd in "Ll":
                nx, ny = num(), num()
                if cmd == "L":
                    x, y = nx, ny
                else:
                    x, y = x + nx, y + ny
                sub.append((x, y))
            elif cmd in "Hh":
                v = num()
                x = v if cmd == "H" else x + v
                sub.append((x, y))
            elif cmd in "Vv":
                v = num()
                y = v if cmd == "V" else y + v
                sub.append((x, y))
            else:
                i += 1
        if len(sub) > 2:
            shapes.append(sub)
    return shapes


def raster(shapes, w, h):
    """Even-odd scanline fill on a w*h grid."""
    grid = [[0] * w for _ in range(h)]
    edges = []
    for poly in shapes:
        for k in range(len(poly)):
            edges.append((poly[k], poly[(k + 1) % len(poly)]))
    for py in range(h):
        sy = py + 0.5
        xs = []
        for (x0, y0), (x1, y1) in edges:
            if y0 == y1:
                continue
            if (y0 <= sy < y1) or (y1 <= sy < y0):
                xs.append(x0 + (sy - y0) * (x1 - x0) / (y1 - y0))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            for px in range(max(0, int(round(a))), min(w, int(round(b)))):
                grid[py][px] ^= 1
    return grid


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--preview", action="store_true")
    ap.add_argument("icons", nargs="+", help="name=path.svg")
    args = ap.parse_args()

    blocks = []
    for spec in args.icons:
        name, path = spec.split("=", 1)
        text = open(path, encoding="utf-8").read()
        size = int(re.search(r'width="(\d+)"', text).group(1))
        grid = raster(parse_paths(text), size, size)

        if args.preview:
            print("%s (%dx%d from %s)" % (name, size, size, path))
            for row in grid:
                print("".join("#" if v else "." for v in row))

        ident = "ICON_" + name.upper().replace("-", "_")
        rows = []
        for row in grid:
            mask = 0
            for px, v in enumerate(row):
                if v:
                    mask |= 1 << px
            rows.append(mask)
        blocks.append(
            "// %s - %s\nstatic const uint32_t %s[%d] = {\n  %s\n};\n"
            % (ident, path.replace("\\", "/"), ident, size,
               ", ".join("0x%06Xu" % r for r in rows)))

    header = (
        "// Generated by tools/svg2header.py - do not edit by hand.\n"
        "//\n"
        "// Icons: Pixelarticons by Halfmoon (https://github.com/halfmage/pixelarticons),\n"
        "// released under the MIT licence. Recoloured at draw time to match this screen.\n"
        "#pragma once\n\n#include <Arduino.h>\n\n"
        "#define UI_ICON_SIZE 24\n\n") + "\n".join(blocks)
    open(args.out, "w", encoding="utf-8", newline="\n").write(header)
    print("wrote %s (%d icons, %d B flash)" % (args.out, len(blocks),
                                              96 * len(blocks)))


if __name__ == "__main__":
    main()
